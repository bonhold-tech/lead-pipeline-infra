enabled=1
gpgkey=https://github.com/rabbitmq/signing-keys/releases/download/3.0/cloudsmith.rabbitmq-server.9F4587F226208342.key
       https://github.com/rabbitmq/signing-keys/releases/download/3.0/rabbitmq-release-signing-key.asc
gpgcheck=1
sslverify=1
sslcacert=/etc/pki/tls/certs/ca-bundle.crt
metadata_expire=300
pkg_gpgcheck=1
autorefresh=1
type=rpm-md
EOF

# Install and start RabbitMQ
dnf makecache -y
dnf install -y logrotate erlang rabbitmq-server
systemctl enable --now rabbitmq-server

# Users: remove guest, create the app user (safe to run more than once)
USERS="$(rabbitmqctl list_users --silent)"
if grep -q '^guest[[:space:]]' <<< "$USERS"; then
  rabbitmqctl delete_user guest
fi
if ! grep -q '^queue_form[[:space:]]' <<< "$USERS"; then
  rabbitmqctl add_user queue_form "$APP_MQ_PASS"
fi
rabbitmqctl set_permissions -p / queue_form ".*" ".*" ".*"

# Firewall: AMQP port open for app01 only
systemctl enable --now firewalld
firewall-cmd --zone=public --add-rich-rule='rule family="ipv4" source address="192.168.56.12" port port="5672" protocol="tcp" accept' --permanent
firewall-cmd --reload